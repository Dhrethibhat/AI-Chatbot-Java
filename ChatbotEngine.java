    private boolean containsTopic(String input, String topic) {

        // Direct topic match
        if (input.contains(topic)) {
            return true;
        }

        // Limited typo correction
        String[] topicWords = topic.split(" ");
        String[] inputWords = input.split(" ");

        for (String topicWord : topicWords) {

            for (String inputWord : inputWords) {

                if (topicWord.length() >= 5 &&
                    inputWord.length() >= 5) {

                    int distance =
                            levenshteinDistance(inputWord, topicWord);

                    if (distance <= 1) {
                        return true;
                    }
                }
            }
        }

        return false;
    }

    private String cleanText(String input) {

        input = input.toLowerCase().trim();

        input = input.replaceAll("[^a-zA-Z0-9 ]", "");

        return input;
    }

    private int levenshteinDistance(String a, String b) {

        int[][] dp =
                new int[a.length() + 1][b.length() + 1];

        for (int i = 0; i <= a.length(); i++) {
            dp[i][0] = i;
        }

        for (int j = 0; j <= b.length(); j++) {
            dp[0][j] = j;
        }

        for (int i = 1; i <= a.length(); i++) {

            for (int j = 1; j <= b.length(); j++) {

                int cost =
                        (a.charAt(i - 1) == b.charAt(j - 1))
                        ? 0 : 1;

                dp[i][j] = Math.min(
                        Math.min(
                                dp[i - 1][j] + 1,
                                dp[i][j - 1] + 1
                        ),
                        dp[i - 1][j - 1] + cost
                );
            }
        }

        return dp[a.length()][b.length()];
    }
